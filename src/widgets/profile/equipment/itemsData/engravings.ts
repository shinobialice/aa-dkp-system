const ENGRAVING_BY_ID = new Map(ENGRAVINGS.map((e) => [e.id, e]));

const OFF_HAND_ONLY_ITEM_IDS = new Set([
  49575, // Позолоченный кинжал равновесия
  55404, // Проклятый кинжал равновесия
  8003136, // Возрожденный кинжал равновесия
]);

function getApplicableTags(
  slotKey: string,
  handedness?: WeaponHandedness,
  itemId?: number,
): string[] {
  switch (slotKey) {
    case "weapon_main":
      if (handedness === "two-handed") return ["two_handed"];
      if (handedness === "one-handed") return ["one_handed"];
      return ["one_handed", "two_handed"];
    case "weapon_off":
      return getOffHandTags(handedness, itemId);
    case "weapon_ranged":
      return ["ranged"];
    case "ring1":
    case "ring2":
      return canEngraveJewelry(itemId) ? ["ring"] : [];
    case "earring1":
    case "earring2":
      return canEngraveJewelry(itemId) ? ["earring"] : [];
    default:
      return [slotKey];
  }
}

function getOffHandTags(
  handedness?: WeaponHandedness,
  itemId?: number,
): string[] {
  if (itemId !== undefined && OFF_HAND_ONLY_ITEM_IDS.has(itemId)) {
    return ["one_handed", "off_hand"];
  }
  if (handedness === "shield") return ["shield"];
  if (handedness === "one-handed") return ["one_handed"];
  return ["one_handed", "shield"];
}

export function isValidEngravingId(
  id: number,
  slotKey: string,
  handedness?: WeaponHandedness,
  itemId?: number,
): boolean {
  const engraving = ENGRAVING_BY_ID.get(id);
  if (!engraving) return false;
  const tags = getApplicableTags(slotKey, handedness, itemId);
  return tags.some((tag) => engraving.slots.includes(tag));
}

export function findEngraving(id: number): Engraving | undefined {
  return ENGRAVING_BY_ID.get(id);
}

export function getEngravingsForSlot(
  slotKey: string,
  handedness?: WeaponHandedness,
  itemId?: number,
): Engraving[] {
  const tags = getApplicableTags(slotKey, handedness, itemId);
  return ENGRAVINGS.filter((e) => tags.some((tag) => e.slots.includes(tag)));
}
